/**
 * «Не загрузилось» вместо «у вас ничего нет».
 *
 * Аудит 14.08.2026: на семи экранах отказ сети гасился пустым обработчиком, и
 * человек в метро читал «Пока пусто» — то есть приложение утверждало, что его
 * выдач, книг и встреч не существует. Отличать «пусто» от «не смогли спросить»
 * обязано само приложение, а не человек.
 *
 * Один компонент на все экраны: раньше такой блок был только в «Моей полке»,
 * и копировать его семь раз означало семь разных формулировок.
 */
export function LoadError({ message, onRetry }: { message?: string; onRetry: () => void }) {
  return (
    <div className="empty">
      <div className="error-banner" role="alert">
        {message || 'Не удалось загрузить. Похоже, нет связи.'}
      </div>
      <button className="btn" onClick={onRetry}>
        Попробовать ещё раз
      </button>
    </div>
  )
}
