import type { Route } from '../App'
import { haptic, openTg } from '../telegram'
import { MAIN_CHAT } from '../links'
import { Icon, type IconName } from './Icon'

/**
 * Инструкция новичка внутри приложения (просьба user 29.07.2026: «перенесём в
 * приложение, без перехода в Notion»).
 *
 * Старая инструкция жила страницей в Notion и описывала ручное заполнение
 * таблиц: войти по почте, нажать Edit, потом New, вписать себя в Owners,
 * потом книгу в All Books, обложку «через Copy image address». Сейчас всё это
 * делает бот с одной фотографии, поэтому текст переписан под нынешний путь —
 * но обещание из оригинала сохранено дословно по смыслу: если лениво или нет
 * времени, пришлите фото, админы внесут сами.
 */
type Step = {
  icon: IconName
  tone: string
  title: string
  body: string
  note?: string
  action?: { label: string; route?: Route; url?: string }
}

export function Guide({ go }: { go: (r: Route) => void }) {
  const steps: Step[] = [
    {
      icon: 'plus',
      tone: '#8DA4EF',
      title: 'Поставьте книгу на полку',
      body:
        'Сфотографируйте обложку — приложение само распознает название и автора. ' +
        'Можно снять сразу стопку или полку корешками: книги разберутся по одной. ' +
        'Ещё можно ввести номер ISBN со штрихкода или вписать всё руками.',
      note: 'Ничего никуда не уезжает: книга остаётся у вас дома. В библиотеке появляется только карточка.',
      action: { label: 'Добавить книгу', route: { name: 'add' } },
    },
    {
      icon: 'bookHeart',
      tone: '#DD93C2',
      title: 'Лениво или нет времени? Мы поможем',
      body:
        'Пришлите фотографию книг или список в чат проекта — админы внесут всё сами. ' +
        'Это нормальный путь, им пользуются многие.',
      action: { label: 'Написать в чат', url: MAIN_CHAT },
    },
    {
      icon: 'book',
      tone: '#E2A336',
      title: 'Найдите, что почитать',
      body:
        'В библиотеке видно, у кого какая книга и в каком городе. Можно искать по названию, ' +
        'автору, жанру и языку, а можно просто описать настроение — подберём.',
      note: 'На занятой книге висит закладка «Книга на руках»: можно попросить сообщить, когда освободится.',
      action: { label: 'Открыть библиотеку', route: { name: 'library' } },
    },
    {
      icon: 'chat',
      tone: '#5BB98B',
      title: 'Договоритесь напрямую',
      body:
        'В карточке книги есть контакт библиотекаря. Напишите, договоритесь, когда и где встретиться ' +
        'и на какой срок берёте книгу. Всё держится на доверии между своими.',
    },
    {
      icon: 'refresh',
      tone: '#EC8E7B',
      title: 'Отдали книгу — отметьте это',
      body:
        'В разделе «У кого моя книга» отметьте, кому и когда отдали. Приложение само напомнит ' +
        'обоим, когда книга загостится, а вернуть её можно одной кнопкой с любой стороны.',
      action: { label: 'У кого моя книга', route: { name: 'loans' } },
    },
    {
      icon: 'crown',
      tone: '#EC9455',
      title: 'Дочитали — оставьте пару слов',
      body:
        'После возврата можно поставить оценку и написать, о чём книга. Это видят все, кто её ищет: ' +
        'так библиотека становится живой, а не просто списком.',
      // кнопка «Мои достижения» убрана (просьба user 4.08.2026): шаг про отзывы,
      // а значки с главной и с полки сняты — вести в них из инструкции незачем
    },
  ]

  return (
    <>
      <h1>Инструкция новичка</h1>
      <div className="sub">
        Всё, что нужно знать, чтобы начать. Если что-то не получается или просто не хочется
        разбираться — напишите в чат или админам, мы поможем.
      </div>

      <div className="guide">
        {steps.map((s, i) => (
          <div key={s.title} className="guide-step card" style={{ ['--tone' as any]: s.tone }}>
            <div className="guide-head">
              <span className="guide-num">{i + 1}</span>
              <div className="ic-tile">
                <Icon name={s.icon} />
              </div>
              <div className="grow">
                <div className="t-sm" style={{ fontWeight: 700 }}>
                  {s.title}
                </div>
              </div>
            </div>
            <p className="guide-body">{s.body}</p>
            {s.note && <p className="guide-note">{s.note}</p>}
            {s.action && (
              <button
                className="btn ghost sm"
                onClick={() => {
                  haptic()
                  if (s.action!.url) openTg(s.action!.url)
                  else if (s.action!.route) go(s.action!.route)
                }}
              >
                {s.action.label}
              </button>
            )}
          </div>
        ))}
      </div>

      <div className="foot">
        Проект держится на людях: книги остаются у своих хозяев, а приложение просто помогает им
        находить друг друга.
      </div>
    </>
  )
}
