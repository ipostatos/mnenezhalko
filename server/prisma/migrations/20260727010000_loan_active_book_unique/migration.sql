-- Запрет «две активные выдачи одной книги» на уровне базы.
--
-- Проверки в коде (createLoan, reopenLoan) есть и обёрнуты в транзакции, но это
-- защита прикладного слоя: любой новый путь записи, забывший про проверку,
-- снова разъедется. Уникальность по activeBookId делает такое состояние
-- невозможным физически.
--
-- Почему отдельная колонка, а не частичный индекс по (bookId) WHERE status =
-- 'active': частичный индекс нельзя описать в схеме Prisma, и каждый следующий
-- `migrate diff` считал бы его лишним и предлагал удалить. Колонка живёт в
-- схеме, ею управляет Prisma, дрейфа нет.
--
-- NULL в SQLite не конфликтует с NULL: закрытых выдач у одной книги может быть
-- сколько угодно, а выдачи без книги (bookId IS NULL) не мешают друг другу.

-- AlterTable
ALTER TABLE "Loan" ADD COLUMN "activeBookId" TEXT;

-- Переносим состояние существующих выдач: активная занимает свою книгу.
-- Сначала данные, потом индекс — на базе с дублями миграция должна упасть
-- на создании индекса, а не оставить половину переноса.
UPDATE "Loan" SET "activeBookId" = "bookId" WHERE "status" = 'active' AND "bookId" IS NOT NULL;

-- CreateIndex
CREATE UNIQUE INDEX "Loan_activeBookId_key" ON "Loan"("activeBookId");
