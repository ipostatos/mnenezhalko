-- Надгробие удалённого библиотекаря и очередь дожима правок книги (аудит 14.08.2026).
--
-- Написано руками, а не сгенерировано: `prisma migrate diff` предлагает для
-- SQLite перестройку таблиц целиком (RedefineTables с копированием всех строк).
-- Для трёх с лишним тысяч книг на живом проде это лишний риск, а изменения
-- здесь чисто добавляющие — SQLite умеет их обычным ALTER TABLE.
--
-- Все три колонки обратно совместимы: прежний код о них не знает и продолжает
-- работать, если релиз придётся откатить.

-- Человек удалил свои данные: запись обезличена навсегда, синк её не трогает.
-- Без этого сорвавшаяся архивация строки в Notion приводила к тому, что
-- ближайший синк возвращал имя, инстаграм и город обратно.
ALTER TABLE "Librarian" ADD COLUMN "erasedAt" DATETIME;

-- Строку владельца не удалось заархивировать в Notion — дожать позже.
-- У книг такой флаг уже был, у владельцев его не хватало.
ALTER TABLE "Librarian" ADD COLUMN "notionArchivePending" BOOLEAN NOT NULL DEFAULT false;

-- Правка полей книги не ушла в Notion — дожать и не дать синку затереть её
-- старыми значениями.
ALTER TABLE "Book" ADD COLUMN "editSyncPending" BOOLEAN NOT NULL DEFAULT false;
