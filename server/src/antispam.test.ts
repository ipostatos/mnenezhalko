/**
 * Антиспам: что считается рекламой, а что живым сообщением.
 *
 * Половина тестов здесь про ЛОЖНЫЕ срабатывания, и это не перестраховка:
 * удалённое в Telegram не вернуть, а книжный чат полон слов «продам»,
 * «отдам» и «пишите в личку», которые в барахолке совершенно нормальны.
 * Цена ошибки в одну сторону и в другую здесь разная.
 *
 * Запуск: npm run test -w server
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { checkSpam, normalizeText, HOMOGLYPHS, SPAM_HARD, SPAM_SOFT } from './antispam.js'

const level = (text: string, ctx = {}) => checkSpam(text, ctx).level

/* ── что должно удаляться ─────────────────────────────────── */

test('классика: крипта, доход, личка, ссылка', () => {
  const v = checkSpam('Заработок на крипте от 500$ в день! Пиши в лс 💰💰💰 t.me/+abc123')
  assert.equal(v.level, 'spam')
  assert.ok(v.score >= SPAM_HARD)
  assert.match(v.reason, /крипта/)
  assert.match(v.reason, /ссылка/)
})

test('наём в «команду» с обещанием дохода', () => {
  assert.equal(
    level('Ищу людей в команду, пассивный доход от 300 евро в неделю, обучу с нуля. Пишите в личку'),
    'spam',
  )
})

test('казино и ставки', () => {
  assert.equal(level('🔥 КАЗИНО 🔥 промокод на депозит, зеркало сайта, успей только сегодня 🚀'), 'spam')
})

test('схема с картами', () => {
  assert.equal(level('Нужен человек с картой, оплата сразу, подробности в лс'), 'spam')
})

/* ── обход фильтра ────────────────────────────────────────── */

test('точки между буквами не спасают', () => {
  assert.equal(level('З.а.р.а.б.о.т.о.к на крипте, доход от 1000$ в месяц, пиши в личку'), 'spam')
})

test('латинские буквы внутри русских слов не спасают', () => {
  // «зaрaбoтoк» с латинскими a и o
  assert.equal(level('Крипта: зaрaбoтoк от 800$ в день, пиши в лс, места ограничены'), 'spam')
})

test('растянутые буквы не спасают', () => {
  assert.equal(level('Зааарабооотоооок на криптееее, доход 500$ в день, пишите в личку'), 'spam')
})

test('приведение текста складывает написания в одно', () => {
  assert.equal(normalizeText('зaрaбoтoк'), normalizeText('заработок'))
  assert.equal(normalizeText('КРИПТА'), normalizeText('крипта'))
})

test('каждая подменная буква действительно подменяется', () => {
  // раньше таблица подмен и шаблон жили порознь, и латинская «o» потерялась
  // именно так: была в таблице, не была в шаблоне
  for (const [from, to] of Object.entries(HOMOGLYPHS)) {
    assert.equal(normalizeText(from), to, `подмена «${from}» не применяется`)
  }
})

/* ── что трогать нельзя ───────────────────────────────────── */

test('объявление в барахолке: «пишите в личку» там нормально', () => {
  assert.equal(
    level('Отдам стеллаж под книги, Варшава, Воля. Самовывоз, пишите в личку', { marketTopic: true }),
    'clean',
  )
  assert.equal(
    level('Продам две книги по 40 zł, состояние отличное. Пишите в личку', { marketTopic: true }),
    'clean',
  )
})

test('разговор о книге про биткоин не реклама', () => {
  assert.equal(level('Читаю сейчас книгу про биткоин и блокчейн, очень интересно объясняют'), 'suspicious')
  // одного семейства признаков для УДАЛЕНИЯ мало никогда
  assert.notEqual(level('Читаю сейчас книгу про биткоин и блокчейн'), 'spam')
})

test('обычная жизнь чата', () => {
  for (const text of [
    'Всем привет! Кто-нибудь читал «Маленького принца» на польском?',
    'Встречаемся в субботу в 18:00 в кафе на Воле, приносите книги',
    'Ищу книгу Достоевского, готова забрать сама или оплатить пересылку 20 zł',
    'Спасибо большое, книга дошла!',
    'А во сколько завтра встреча?',
  ]) {
    assert.equal(level(text), 'clean', `ложное срабатывание: ${text}`)
  }
})

test('пустое сообщение', () => {
  assert.equal(level(''), 'clean')
  assert.equal(level('   '), 'clean')
})

/* ── контекст автора ──────────────────────────────────────── */

test('свой человек с полкой получает поблажку', () => {
  const text = 'Могу подсказать по инвестициям в книги, пишите в личку'
  const stranger = checkSpam(text)
  const known = checkSpam(text, { known: true })
  assert.ok(known.score < stranger.score, 'у своего счёт ниже')
})

test('первое сообщение незнакомца со ссылкой подозрительнее', () => {
  const text = 'Всем привет, вот полезный канал t.me/+xyz789'
  const old = checkSpam(text, { firstSeen: false })
  const fresh = checkSpam(text, { firstSeen: true })
  assert.ok(fresh.score > old.score)
})

/* ── границы решения ──────────────────────────────────────── */

test('одного семейства признаков для удаления недостаточно никогда', () => {
  // даже с большим весом: «эскорт» один, без второго признака, только спорное
  const v = checkSpam('эскорт')
  assert.notEqual(v.level, 'spam')
})

test('пороги согласованы: удаление строго выше показа', () => {
  assert.ok(SPAM_HARD > SPAM_SOFT, 'иначе спорное удалялось бы наравне с явным')
})

test('разбор всегда объясним', () => {
  const v = checkSpam('Заработок на крипте от 500$ в день, пиши в лс')
  assert.ok(v.signals.length >= 3)
  assert.ok(v.reason.includes('+'), 'причина перечисляет признаки, а не «спам»')
  for (const s of v.signals) assert.ok(s.title && s.weight > 0)
})
