/**
 * Антиспам: что считается рекламой, а что живым сообщением.
 *
 * Половина тестов здесь про ЛОЖНЫЕ срабатывания, и это не перестраховка:
 * удалённое в Telegram не вернуть, а книжный чат полон слов «продам»,
 * «отдам» и «пишите в личку», которые в барахолке совершенно нормальны.
 * Цена ошибки в одну сторону и в другую здесь разная.
 *
 * Запуск: npm run test -w server
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { checkSpam, normalizeText, CHAR_VARIANTS, SPAM_HARD, SPAM_SOFT } from './antispam.js'

const level = (text: string, ctx = {}) => checkSpam(text, ctx).level

/* ── что должно удаляться ─────────────────────────────────── */

test('классика: крипта, доход, личка, ссылка', () => {
  const v = checkSpam('Заработок на крипте от 500$ в день! Пиши в лс 💰💰💰 t.me/+abc123')
  assert.equal(v.level, 'spam')
  assert.ok(v.score >= SPAM_HARD)
  assert.match(v.reason, /крипта/)
  assert.match(v.reason, /ссылка/)
})

test('наём в «команду» с обещанием дохода', () => {
  assert.equal(
    level('Ищу людей в команду, пассивный доход от 300 евро в неделю, обучу с нуля. Пишите в личку'),
    'spam',
  )
})

test('казино и ставки', () => {
  assert.equal(level('🔥 КАЗИНО 🔥 промокод на депозит, зеркало сайта, успей только сегодня 🚀'), 'spam')
})

test('схема с картами', () => {
  assert.equal(level('Нужен человек с картой, оплата сразу, подробности в лс'), 'spam')
})

/* ── обход фильтра ────────────────────────────────────────── */

test('точки между буквами не спасают', () => {
  assert.equal(level('З.а.р.а.б.о.т.о.к на крипте, доход от 1000$ в месяц, пиши в личку'), 'spam')
})

test('латинские буквы внутри русских слов не спасают', () => {
  // «зaрaбoтoк» с латинскими a и o
  assert.equal(level('Крипта: зaрaбoтoк от 800$ в день, пиши в лс, места ограничены'), 'spam')
})

test('растянутые буквы не спасают', () => {
  assert.equal(level('Зааарабооотоооок на криптееее, доход 500$ в день, пишите в личку'), 'spam')
})

test('приведение текста складывает написания в одно', () => {
  // приведение отвечает только за регистр, невидимки, польские диакритики и
  // растянутые буквы; подмену похожих букв разбирают шаблоны слов
  assert.equal(normalizeText('КРИПТА'), 'крипта')
  assert.equal(normalizeText('zakład'), 'zaklad')
  assert.equal(normalizeText('зааааработок'), 'заработок')
})

test('одно слово, записанное четырьмя способами, ловится одинаково', () => {
  // это один и тот же приём обхода, поэтому и разбирается одной таблицей
  const tail = ' от 500$ в день, пиши в лс'
  for (const word of ['заработок', 'зaрaбoтoк', '3аработок', 'zarabotok']) {
    assert.equal(checkSpam(word + tail).level, 'spam', `не поймано написание: ${word}`)
  }
})

test('в таблице написаний нет пустых и повторяющихся вариантов', () => {
  // таблица — единственный источник правды для шаблонов: пустой вариант
  // превратил бы шаблон в «совпадает с чем угодно»
  for (const [ch, alts] of Object.entries(CHAR_VARIANTS)) {
    assert.ok(alts.length > 0, `нет вариантов для «${ch}»`)
    assert.ok(alts.every((a) => a.length > 0), `пустой вариант у «${ch}»`)
    assert.equal(new Set(alts).size, alts.length, `повтор в вариантах «${ch}»`)
    assert.ok(alts.includes(ch), `буква «${ch}» не совпадает сама с собой`)
  }
})

/* ── что трогать нельзя ───────────────────────────────────── */

test('объявление в барахолке: «пишите в личку» там нормально', () => {
  assert.equal(
    level('Отдам стеллаж под книги, Варшава, Воля. Самовывоз, пишите в личку', { marketTopic: true }),
    'clean',
  )
  assert.equal(
    level('Продам две книги по 40 zł, состояние отличное. Пишите в личку', { marketTopic: true }),
    'clean',
  )
})

test('разговор о книге про биткоин не реклама', () => {
  assert.equal(level('Читаю сейчас книгу про биткоин и блокчейн, очень интересно объясняют'), 'clean')
  // а вот та же крипта без единого книжного слова — уже повод показать админам
  assert.equal(level('Биткоин, блокчейн, трейдинг — подробности у меня'), 'suspicious')
  // одного семейства признаков для УДАЛЕНИЯ мало никогда
  assert.notEqual(level('Биткоин, блокчейн, трейдинг'), 'spam')
})

test('обычная жизнь чата', () => {
  for (const text of [
    'Всем привет! Кто-нибудь читал «Маленького принца» на польском?',
    'Встречаемся в субботу в 18:00 в кафе на Воле, приносите книги',
    'Ищу книгу Достоевского, готова забрать сама или оплатить пересылку 20 zł',
    'Спасибо большое, книга дошла!',
    'А во сколько завтра встреча?',
  ]) {
    assert.equal(level(text), 'clean', `ложное срабатывание: ${text}`)
  }
})

test('пустое сообщение', () => {
  assert.equal(level(''), 'clean')
  assert.equal(level('   '), 'clean')
})

/* ── контекст автора ──────────────────────────────────────── */

test('свой человек с полкой получает поблажку', () => {
  const text = 'Пассивный доход от крипты, пишите в личку'
  const stranger = checkSpam(text)
  const known = checkSpam(text, { known: true })
  assert.ok(known.score < stranger.score, 'у своего счёт ниже')
})

test('первое сообщение незнакомца со ссылкой подозрительнее', () => {
  const text = 'Всем привет, вот полезный канал t.me/+xyz789'
  const old = checkSpam(text, { firstSeen: false })
  const fresh = checkSpam(text, { firstSeen: true })
  assert.ok(fresh.score > old.score)
})

/* ── границы решения ──────────────────────────────────────── */

test('одного семейства признаков для удаления недостаточно никогда', () => {
  // даже с большим весом: «эскорт» один, без второго признака, только спорное
  const v = checkSpam('эскорт')
  assert.notEqual(v.level, 'spam')
})

test('пороги согласованы: удаление строго выше показа', () => {
  assert.ok(SPAM_HARD > SPAM_SOFT, 'иначе спорное удалялось бы наравне с явным')
})

test('разбор всегда объясним', () => {
  const v = checkSpam('Заработок на крипте от 500$ в день, пиши в лс')
  assert.ok(v.signals.length >= 3)
  assert.ok(v.reason.includes('+'), 'причина перечисляет признаки, а не «спам»')
  for (const s of v.signals) assert.ok(s.title && s.weight > 0)
})

/* ── ложные срабатывания 19.08.2026 ───────────────────────── */

/**
 * Восемь отметок «оставить сообщение» в журнале модерации за 19 августа.
 * Сами тексты в журнале не сохранились (это чиним отдельно), но причина
 * воспроизводится на живых данных: словарь сравнивался ПОДСТРОКОЙ, поэтому
 * «ставк» весом 5 находилась внутри «доставки» и «подставки», а «крипт» —
 * внутри «Криптономикона», который лежит в каталоге проекта.
 */
test('слово из словаря не должно находиться внутри другого слова', () => {
  for (const text of [
    'Отдам книги, могу организовать доставку по Варшаве',
    'Продам подставку для книг, 30 zł',
    'Служба доставки книг — Карстен Себастиан Хенн, отличный роман',
    'Читаю «Криптономикон» Стивенсона, отдам почитать',
  ]) {
    assert.equal(level(text), 'clean', `ложное срабатывание: ${text}`)
  }
})

/**
 * Чат живёт в Польше, и быт в нём обсуждают наравне с книгами. Такие слова
 * из словаря убраны в отдельную семью с весом 1: сами по себе карточку не
 * поднимают, но в связке с обещанием дохода считаются.
 */
test('бытовой разговор экспатов не реклама', () => {
  for (const text of [
    'Ребят, кто знает хороший обменник валют в центре? И ещё вопрос про депозит за квартиру',
    'У кого есть промокод на Empik? Хочу заказать книгу',
    'Потерял кошелёк с картой в трамвае, если кто найдёт — напишите мне',
    'Ищу подработку на выходные, может кто подскажет',
    'Слот на 18:00 свободен, записывайтесь',
    'Кто пойдёт первым читать? Напиши мне, договоримся',
  ]) {
    assert.equal(level(text), 'clean', `ложное срабатывание: ${text}`)
  }
})

/**
 * Книги про деньги — законная тема книжного чата, и словарь обязан это
 * различать: «пассивный доход» на обложке и «пассивный доход» в объявлении
 * о наборе в команду — разные сообщения.
 */
test('книга про деньги — не реклама денег', () => {
  for (const text of [
    'Посоветуйте книгу про инвестиции и пассивный доход',
    'Богатый папа бедный папа — книга про финансовую свободу, отдам почитать',
    'Читаю книгу про биткоин и блокчейн, интересно объясняют',
    'Вложение в себя — лучшая инвестиция, так пишет автор этой книги',
  ]) {
    assert.equal(level(text), 'clean', `ложное срабатывание: ${text}`)
  }
})

