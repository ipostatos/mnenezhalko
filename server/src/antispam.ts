/**
 * Антиспам для чата проекта.
 *
 * Ловим то, что приходит в книжное сообщество чаще всего: «заработок на крипте»,
 * «доход от 500$ в день», ставки и казино, наём «людей с картой», зазывалы
 * в личку со ссылкой на канал.
 *
 * Устройство. Здесь только РЕШЕНИЕ, без единого действия: на входе текст и
 * немного контекста, на выходе оценка и объяснение. Удаляет и пишет админам
 * бот (bot.ts), а тестировать можно всё на живых текстах без Telegram.
 *
 * Почему счёт баллами, а не одним стоп-словом. Слово «продам» в барахолке
 * нормально, «пишите в личку» нормально, ссылка нормальна. Спам собирается из
 * НЕСКОЛЬКИХ признаков сразу, и именно сумма отличает объявление о книгах от
 * «крипта + доход + личка + ссылка».
 *
 * Почему без ИИ. Решение должно быть мгновенным, бесплатным и объяснимым:
 * админ видит, за что именно снято сообщение, и может спорить с правилом.
 * Модель тут дала бы «мне кажется» без разбора и на каждое сообщение чата.
 */

/* ── приведение текста к сравнимому виду ──────────────────── */

/**
 * Латиница и цифры, неотличимые от кириллицы на глаз: ими и подменяют буквы,
 * чтобы стоп-слово не совпало («зaрaбoтoк» с латинскими a и o).
 *
 * ⚠️ Шаблон СОБИРАЕТСЯ из этой таблицы, а не пишется рядом руками: сначала
 * так и было, латинская «o» осталась в таблице и потерялась в шаблоне, и
 * подмена через неё проходила насквозь. Теперь разойтись нечему.
 */
export const HOMOGLYPHS: Record<string, string> = {
  a: 'а', c: 'с', e: 'е', o: 'о', p: 'р', x: 'х', y: 'у', k: 'к', m: 'м', t: 'т',
  b: 'в', h: 'н', i: 'и', 3: 'е', 0: 'о', 4: 'ч', 6: 'б', '@': 'а', $: 'ѕ',
}

const HOMOGLYPH_RE = new RegExp(
  `[${Object.keys(HOMOGLYPHS)
    .map((ch) => ch.replace(/[$@]/g, '\\$&'))
    .join('')}]`,
  'g',
)

/**
 * Спам пишут так, чтобы стоп-слова не совпали: латинская «a» в русском слове,
 * ноль вместо «о», точки и пробелы между буквами. Приводим к одному виду и
 * текст, и сами слова из списков (это важно: списки нормализуются тем же
 * кодом, иначе английские слова после подмены букв перестали бы совпадать).
 */
export function normalizeText(raw: string): string {
  let s = raw.toLowerCase()
  // невидимые символы: ими разрывают слова прямо посреди буквы
  s = s.replace(/[​-‏⁠﻿­]/g, '')
  s = s.replace(HOMOGLYPH_RE, (ch) => HOMOGLYPHS[ch] ?? ch)
  // «зааааработок» — растянутые буквы
  s = s.replace(/(.)\1{2,}/g, '$1')
  return s
}

/** Тот же текст без единого разделителя: ловит «з.а.р.а.б.о.т.о.к». */
function squeeze(normalized: string): string {
  return normalized.replace(/[^\p{L}\p{N}]/gu, '')
}

