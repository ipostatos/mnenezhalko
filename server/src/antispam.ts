/**
 * Антиспам для чата проекта.
 *
 * Ловим то, что приходит в книжное сообщество чаще всего: «заработок на крипте»,
 * «доход от 500$ в день», ставки и казино, наём «людей с картой», зазывалы
 * в личку со ссылкой на канал.
 *
 * Устройство. Здесь только РЕШЕНИЕ, без единого действия: на входе текст и
 * немного контекста, на выходе оценка и объяснение. Удаляет и пишет админам
 * бот (bot.ts), а тестировать можно всё на живых текстах без Telegram.
 *
 * Почему счёт баллами, а не одним стоп-словом. Слово «продам» в барахолке
 * нормально, «пишите в личку» нормально, ссылка нормальна. Спам собирается из
 * НЕСКОЛЬКИХ признаков сразу, и именно сумма отличает объявление о книгах от
 * «крипта + доход + личка + ссылка».
 *
 * Почему без ИИ. Решение должно быть мгновенным, бесплатным и объяснимым:
 * админ видит, за что именно снято сообщение, и может спорить с правилом.
 * Модель тут дала бы «мне кажется» без разбора и на каждое сообщение чата.
 *
 * ⚠️ Цена ошибки в две стороны разная. Пропущенная реклама живёт в чате до
 * прихода админа; удалённое сообщение человека не вернуть никогда. Поэтому
 * при сомнении фильтр обязан ошибаться в сторону «оставить».
 */

/* ── приведение текста к сравнимому виду ──────────────────── */

/** Невидимые символы: ими разрывают слово прямо посреди буквы. */
const INVISIBLE = /[​-‏⁠﻿­]/g

/**
 * Польские диакритики сводим к базовой букве: чат живёт в Польше, и одно и то
 * же слово пишут и «zakład», и «zaklad». Списки при этом можно писать как
 * угодно — они проходят через это же приведение.
 */
const PL_FOLD: Record<string, string> = {
  ą: 'a', ć: 'c', ę: 'e', ł: 'l', ń: 'n', ó: 'o', ś: 's', ź: 'z', ż: 'z',
}

/**
 * Приводит текст к сравнимому виду: регистр, невидимки, диакритики и
 * растянутые буквы («зааааработок»).
 *
 * ⚠️ Подмену похожих букв здесь НЕ делаем — она ушла в шаблоны слов, см.
 * CHAR_VARIANTS. Односторонняя подмена в тексте была неисправима по своей
 * природе: цифра «3» стоит и вместо «з», и вместо «е», а выбрать в тексте
 * можно только одно. Из-за этого «3aрaбoтoк» превращался в «еаработок» и
 * проходил насквозь.
 */
export function normalizeText(raw: string): string {
  let s = raw.toLowerCase()
  s = s.replace(INVISIBLE, '')
  s = s.replace(/[ąćęłńóśźż]/g, (c) => PL_FOLD[c] ?? c)
  s = s.replace(/(.)\1{2,}/g, '$1')
  return s
}

/**
 * «з.а.р.а.б.о.т.о.к» и «З А Р А Б О Т О К» — убираем разделители, но ТОЛЬКО
 * внутри длинных цепочек «буква-разделитель-буква».
 *
 * ⚠️ Раньше разделители выбрасывались из всего текста разом, и вместе с
 * точками пропадали пробелы между обычными словами: «могу организовать»
 * склеивалось в одно слово, а с ним пропадали границы слов — из-за этого
 * «ставк» находилась внутри «доставки».
 */
export function deobfuscate(normalized: string): string {
  return normalized.replace(/(?:\p{L}[^\p{L}\p{N}]){3,}\p{L}/gu, (run) =>
    run.replace(/[^\p{L}\p{N}]/gu, ''),
  )
}

