/** Сокращалки ссылок и приглашения в закрытые каналы: в книжном чате им нечего делать. */
const BAD_LINKS =
  /(t\.me\/\+|t\.me\/joinchat|telegra\.ph|bit\.ly|tinyurl|cutt\.ly|goo\.gl|is\.gd|clck\.ru|vk\.cc|wa\.me|whatsapp\.com)/i

/** «от 500$», «300 евро в день», «1000 zł в неделю». Считаем по СЫРОМУ тексту. */
const MONEY =
  /(\d[\d\s.,]{1,8})\s*(\$|€|usd|eur|евро|доллар|долл|zł|zl|злот|руб|₽|тыс)/i
const MONEY_PER_TIME =
  /\d[\d\s.,]{0,8}\s*(\$|€|usd|eur|евро|доллар|долл|zł|zl|злот|руб|₽|тыс)?\s*(в день|в сутки|в неделю|в месяц|\/день|\/мес)/i

export type SpamSignal = { key: string; title: string; weight: number }

export type SpamVerdict = {
  score: number
  /** clean — ничего, suspicious — карточка админам, spam — удаляем */
  level: 'clean' | 'suspicious' | 'spam'
  signals: SpamSignal[]
  /** готовая фраза для карточки админам: «крипта + доход + личка» */
  reason: string
}

export type SpamContext = {
  /** сообщение пришло в тему барахолки: там «продам» и «пишите в личку» нормальны */
  marketTopic?: boolean
  /** человек уже в проекте: есть книги на полке или он библиотекарь */
  known?: boolean
  /** это его первое сообщение, которое мы видим */
  firstSeen?: boolean
}

/** Порог удаления и порог «показать админам». Меняются через окружение. */
export const SPAM_HARD = Number(process.env.ANTISPAM_HARD || 8)
export const SPAM_SOFT = Number(process.env.ANTISPAM_SOFT || 4)

/**
 * Оценивает сообщение.
 *
 * Возвращает и счёт, и разбор: карточка админам обязана объяснять решение,
 * иначе спорить с ним невозможно, а настраивать пороги придётся вслепую.
 */
export function checkSpam(text: string, ctx: SpamContext = {}): SpamVerdict {
  const raw = (text ?? '').trim()
  const signals: SpamSignal[] = []
  if (!raw) return { score: 0, level: 'clean', signals, reason: '' }

  const norm = normalizeText(raw)
  const squeezed = squeeze(norm)

  for (const family of NORMALIZED_FAMILIES) {
    const hit = family.needles.some(
      (n) => norm.includes(n.plain) || (n.squeezed.length >= 6 && squeezed.includes(n.squeezed)),
    )
    if (!hit) continue
    let weight = family.weight
    // в барахолке зовут в личку по делу: «отдам полку, пишите»
    if (family.key === 'dm' && ctx.marketTopic) weight = 0
    if (weight) signals.push({ key: family.key, title: family.title, weight })
  }

  if (BAD_LINKS.test(raw)) {
    signals.push({ key: 'link', title: 'ссылка-приглашение или сокращалка', weight: 3 })
  }
  if (MONEY_PER_TIME.test(raw)) {
    signals.push({ key: 'money_rate', title: 'деньги в единицу времени', weight: 3 })
  } else if (MONEY.test(raw) && !ctx.marketTopic) {
    // сумма сама по себе не улика, но вне барахолки она редко к месту
    signals.push({ key: 'money', title: 'сумма в сообщении', weight: 1 })
  }

  // денежные эмодзи пачкой: у живых людей так не бывает
  const moneyEmoji = (raw.match(/[💰💵💸🤑🚀🔥]/gu) ?? []).length
  if (moneyEmoji >= 3) {
    signals.push({ key: 'emoji', title: 'ряд денежных эмодзи', weight: 2 })
  }

  let score = signals.reduce((sum, s) => sum + s.weight, 0)

  // Кто пишет, важно не меньше, чем что пишет: у своего человека с полкой
  // порог выше, у первого сообщения незнакомца со ссылкой ниже.
  if (ctx.known) score -= 3
  if (ctx.firstSeen && signals.some((s) => s.key === 'link')) score += 2
  score = Math.max(0, score)

  // Одиночный признак не приговор: «крипта» встречается и в разговоре о книгах
  // («читаю книгу про биткоин»), поэтому одного семейства для удаления мало.
  const families = signals.filter((s) => s.weight > 0 && s.key !== 'money').length
  const level: SpamVerdict['level'] =
    score >= SPAM_HARD && families >= 2 ? 'spam' : score >= SPAM_SOFT ? 'suspicious' : 'clean'

  return {
    score,
    level,
    signals,
    reason: signals.map((s) => s.title).join(' + ') || 'ничего подозрительного',
  }
}
