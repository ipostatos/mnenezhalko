/**
 * Для каждой буквы — все написания, которыми её подменяют: похожая буква
 * другого алфавита, цифра и латинская транслитерация.
 *
 * Одна таблица закрывает сразу три обхода фильтра, и это не совпадение, а
 * причина её существования: «зaрaбoтoк» (латиница внутри русского слова),
 * «3аработок» (цифра вместо буквы) и «zarabotok» (транслит целиком) — это
 * один и тот же приём: записать слово так, чтобы оно читалось глазом, но не
 * совпало со списком. Поэтому отдельного словаря транслита НЕТ, он получается
 * из этой таблицы сам.
 */
const CHAR_VARIANTS_RAW: Record<string, string> = {
  а: 'а a @', б: 'б b 6', в: 'в v b w', г: 'г g', д: 'д d', е: 'е ё e 3',
  ё: 'ё е e 3 yo', ж: 'ж zh j', з: 'з z 3', и: 'и i y', й: 'й y j i',
  к: 'к k', л: 'л l', м: 'м m', н: 'н n h', о: 'о o 0', п: 'п p n',
  р: 'р r p', с: 'с s c', т: 'т t 7', у: 'у u y', ф: 'ф f', х: 'х h x kh',
  ц: 'ц c ts', ч: 'ч ch 4', ш: 'ш sh w', щ: 'щ sch shch sh', ы: 'ы y',
  э: 'э e', ю: 'ю yu ju', я: 'я ya ja',
  a: 'a а @', b: 'b б в', c: 'c с', d: 'd д', e: 'e е 3', f: 'f ф', g: 'g г',
  h: 'h н х', i: 'i и 1', j: 'j й', k: 'k к', l: 'l л 1', m: 'm м', n: 'n н п',
  o: 'o о 0', p: 'p р п', q: 'q', r: 'r р', s: 's с $', t: 't т 7', u: 'u у',
  v: 'v в', w: 'w в ш', x: 'x х', y: 'y у ы', z: 'z з 3',
}

export const CHAR_VARIANTS: Record<string, string[]> = Object.fromEntries(
  Object.entries(CHAR_VARIANTS_RAW).map(([ch, alts]) => [
    ch,
    // длинные написания раньше коротких: «ch» должно примеряться до «ч»
    [...new Set(alts.split(' '))].sort((a, b) => b.length - a.length),
  ]),
)

const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/**
 * Сколько букв разрешено дописать в конце слова.
 *
 * ⚠️ Это и есть починка главной причины ложных срабатываний. Раньше слово из
 * списка искалось ПОДСТРОКОЙ где угодно, и «ставк» весом 5 находилась внутри
 * «доставки» и «подставки», а «крипт» — внутри «Криптономикона», который
 * лежит в каталоге проекта. Теперь слово обязано начинаться с начала слова, а
 * хвост ограничен окончанием: «ставка», «ставками» — да, «криптономикон»
 * (хвост в восемь букв) — нет.
 */
function tailAllowance(word: string): number {
  const letters = (word.match(/\p{L}/gu) ?? []).length
  if (letters >= 6) return 4
  if (letters >= 4) return 3
  return 0
}

/** Собирает из слова шаблон, терпимый к подменам букв и к разделителям. */
function needleRegex(word: string): RegExp {
  let src = ''
  for (const ch of normalizeText(word)) {
    if (/[\p{L}\p{N}]/u.test(ch)) {
      const alts = CHAR_VARIANTS[ch]
      src += alts ? `(?:${alts.map(escapeRe).join('|')})` : escapeRe(ch)
    } else {
      // пробел или дефис внутри выражения: «пиши в лс», «praca zdalna»
      src += '[^\\p{L}\\p{N}]{1,3}'
    }
  }
  const tail = tailAllowance(word)
  return new RegExp(`(?<![\\p{L}\\p{N}])${src}\\p{L}{0,${tail}}(?![\\p{L}])`, 'u')
}

