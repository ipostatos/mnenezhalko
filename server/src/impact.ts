/**
 * «Сколько мы сберегли вместе» (issue #13): деньги, бумага, деревья.
 *
 * Три решения, которые здесь важнее кода:
 *
 * 1. **Считаем обмены, а не книги на полках.** Полка — это возможность, а
 *    польза появляется в тот момент, когда книга ушла из рук в руки: человек
 *    прочитал её вместо того, чтобы купить новую. Поэтому основа — выдачи
 *    (`Loan`), и цифра растёт с каждым новым обменом.
 * 2. **Коэффициенты — честные оценки, а не расчёт.** Каждый вынесен в
 *    константу с источником прикидки прямо здесь, а в интерфейсе рядом с
 *    цифрой стоит «примерно» и раскрывается формула. Спорность методики —
 *    известный риск (issue #13), и прятать её было бы хуже, чем показать.
 * 3. **Считаем осторожно, в меньшую сторону.** Средняя цена книги в Польше по
 *    отраслевым обзорам ближе к 45 злотым, берём 40; бумаги в книге около
 *    трети килограмма, берём 0.3. Цифра, которую легко оспорить в большую
 *    сторону, вредит доверию сильнее, чем скромная.
 *
 * Функция расчёта чистая: на входе число обменов, на выходе числа. Поэтому
 * методику проверяет тест, а не наблюдение за продом (impact.test.ts).
 */
import { prisma } from './db.js'

/**
 * Средняя цена новой книги в Польше, злотых. Отраслевые обзоры рынка книги
 * дают ~45 zł за новинку в 2024–2025; берём 40 — заниженная оценка честнее.
 */
export const AVG_BOOK_PRICE_PLN = 40

/**
 * Бумаги в одной книге, кг. Типичная книга в мягкой обложке весит ~350 г, из
 * них бумага — почти всё. Берём 0.3 кг.
 */
export const PAPER_PER_BOOK_KG = 0.3

/**
 * Бумаги из одного дерева, кг. Распространённая оценка: тонна бумаги — это
 * примерно 17 деревьев, то есть около 60 кг бумаги на дерево.
 */
export const PAPER_PER_TREE_KG = 60

export type Impact = {
  /** сколько раз книга сходила из рук в руки */
  exchanges: number
  /** примерно столько злотых не потрачено на новые книги */
  moneyPln: number
  /** примерно столько килограммов бумаги не понадобилось напечатать */
  paperKg: number
  /** и столько деревьев осталось расти */
  trees: number
  /** коэффициенты уезжают на клиент: пояснение к цифрам собирается из них */
  basis: {
    pricePln: number
    paperPerBookKg: number
    paperPerTreeKg: number
  }
}

/**
 * Пересчёт оценки из числа обменов. Отдельно от базы: методику видно целиком,
 * и её можно проверить, не поднимая SQLite.
 */
export function computeImpact(exchanges: number): Impact {
  const safe = Number.isFinite(exchanges) && exchanges > 0 ? Math.floor(exchanges) : 0
  const paperKg = safe * PAPER_PER_BOOK_KG
  return {
    exchanges: safe,
    moneyPln: Math.round(safe * AVG_BOOK_PRICE_PLN),
    // килограммы с одним знаком: «12.3 кг» читается, «12.300000000000001» — нет
    paperKg: Math.round(paperKg * 10) / 10,
    // деревья — с двумя знаками: одно дерево это две сотни книг, и при округлении
    // до десятых первые полторы сотни обменов давали бы честный, но обидный ноль.
    // Показывать эту цифру или ещё рано — решает интерфейс
    trees: Math.round((paperKg / PAPER_PER_TREE_KG) * 100) / 100,
    basis: {
      pricePln: AVG_BOOK_PRICE_PLN,
      paperPerBookKg: PAPER_PER_BOOK_KG,
      paperPerTreeKg: PAPER_PER_TREE_KG,
    },
  }
}

/**
 * Сколько обменов состоялось. Считаем все выдачи: и закрытые, и те, что прямо
 * сейчас на руках — книга уже сходила к человеку, польза уже случилась.
 */
export async function countExchanges(): Promise<number> {
  return prisma.loan.count()
}

/**
 * Готовый агрегат для главной. Держим ответ несколько минут: цифра меняется
 * редко, а на главную заходят все.
 */
const CACHE_MS = 5 * 60_000
let cache: { at: number; value: Impact } | null = null

/** Обменов стало больше — покажем свежую цифру, не дожидаясь конца кэша. */
export const invalidateImpact = () => {
  cache = null
}

export async function impact(now = Date.now()): Promise<Impact> {
  if (cache && now - cache.at < CACHE_MS) return cache.value
  const value = computeImpact(await countExchanges())
  cache = { at: now, value }
  return value
}
